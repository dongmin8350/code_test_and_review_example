def add(a, b):
    """Add two numbers."""
    return a + b

def minus(a, b):
    """Subtract b from a."""
    return a - b

def multiply(a, b):
    """Multiply a and b."""
    return a * b

def square(a, b):
    """a to the power of b"""
    return a ** b

def divide(a, b):
    """divide a by b"""
    return a / b
